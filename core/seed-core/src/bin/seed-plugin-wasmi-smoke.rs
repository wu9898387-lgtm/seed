use seed_core::{
    capability::Capability,
    id::PluginId,
    plugin::{PluginManifest, PluginPermission, PluginVersion},
    wasm_runtime::{WasmiPluginRuntime, HOST_ALLOW},
};

const CAPABILITY_PLUGIN: &[u8] = &[
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x0a, 0x02, 0x60, 0x01, 0x7f, 0x01, 0x7f,
    0x60, 0x00, 0x01, 0x7f, 0x02, 0x1b, 0x01, 0x04, 0x73, 0x65, 0x65, 0x64, 0x12, 0x63, 0x61, 0x70,
    0x61, 0x62, 0x69, 0x6c, 0x69, 0x74, 0x79, 0x5f, 0x61, 0x6c, 0x6c, 0x6f, 0x77, 0x65, 0x64, 0x00,
    0x00, 0x03, 0x02, 0x01, 0x01, 0x07, 0x0b, 0x01, 0x07, 0x6f, 0x6e, 0x5f, 0x6c, 0x6f, 0x61, 0x64,
    0x00, 0x01, 0x0a, 0x08, 0x01, 0x06, 0x00, 0x41, 0x01, 0x10, 0x00, 0x0b,
];

const STATE_PLUGIN: &[u8] = &[
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x10, 0x03, 0x60, 0x02, 0x7f, 0x7f, 0x01,
    0x7f, 0x60, 0x01, 0x7f, 0x01, 0x7f, 0x60, 0x00, 0x01, 0x7f, 0x02, 0x23, 0x02, 0x04, 0x73, 0x65,
    0x65, 0x64, 0x09, 0x73, 0x74, 0x61, 0x74, 0x65, 0x5f, 0x70, 0x75, 0x74, 0x00, 0x00, 0x04, 0x73,
    0x65, 0x65, 0x64, 0x09, 0x73, 0x74, 0x61, 0x74, 0x65, 0x5f, 0x67, 0x65, 0x74, 0x00, 0x01, 0x03,
    0x02, 0x01, 0x02, 0x07, 0x0b, 0x01, 0x07, 0x6f, 0x6e, 0x5f, 0x6c, 0x6f, 0x61, 0x64, 0x00, 0x02,
    0x0a, 0x0f, 0x01, 0x0d, 0x00, 0x41, 0x07, 0x41, 0x2a, 0x10, 0x00, 0x1a, 0x41, 0x07, 0x10, 0x01,
    0x0b,
];

fn main() {
    let runtime = WasmiPluginRuntime::new();
    let mut manifest = PluginManifest::new(
        PluginId::from_bytes([0x71; 32]),
        PluginVersion {
            major: 0,
            minor: 1,
            patch: 0,
        },
    );
    manifest
        .permissions
        .push(PluginPermission::EvaluateCapability(
            Capability::MemberRemove,
        ));
    manifest.permissions.push(PluginPermission::ScopedStorage);

    let mut governance = runtime
        .instantiate(manifest.clone(), CAPABILITY_PLUGIN)
        .expect("instantiate governance plugin");
    assert_eq!(
        governance.call_i32("on_load").expect("capability Host ABI"),
        HOST_ALLOW
    );

    let mut stateful = runtime
        .instantiate(manifest, STATE_PLUGIN)
        .expect("instantiate state plugin");
    assert_eq!(stateful.call_i32("on_load").expect("state Host ABI"), 42);
    assert_eq!(stateful.scoped_state(7), Some(42));

    println!(
        "seed-plugin-wasmi-smoke capability=allow state=42 fuel_remaining={}",
        stateful.remaining_fuel().expect("fuel enabled")
    );
}
